"""Модуль с функциями для форматирования текста и чисел."""


def format_kopeks(kopeks: int) -> str:
    """Форматирует число копеек в строку с рублями.

    Args:
        kopeks: Количество копеек.

    Returns:
        Отформатированная строка с суммой в рублях.
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Форматирует текст заголовка, добавляя символы по краям.

    Args:
        text: Исходный текст заголовка.
        width: Общая ширина строки после форматирования. По умолчанию 40.

    Returns:
        Отформатированная строка с добавленными символами.
    """
    return text.center(width, "=")